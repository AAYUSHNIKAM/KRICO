import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/player_model.dart';

/// Parent-child linking. Parents can either create a child profile that they
/// manage, or link an already self-registered player account by email.
class ParentService {
  ParentService(this._firestore);

  final FirebaseFirestore _firestore;

  /// Creates a new child player record linked to [parentId] and returns the
  /// generated player id.
  Future<String> addChild({
    required String parentId,
    required String name,
    int? age,
    List<String>? sports,
    double? monthlyLimit,
    bool? requireApproval,
  }) async {
    final docRef = _firestore.collection('players').doc();
    final data = <String, dynamic>{
      'playerId': docRef.id,
      'parentId': parentId,
      'name': name,
      'points': 0,
      'rank': 0,
      'championshipWins': 0,
      'tournamentPoints': 0,
      'level': 'Beginner',
      'monthlyLimit': monthlyLimit ?? 5000.0,
      'requireApproval': requireApproval ?? true,
      'createdAt': FieldValue.serverTimestamp(),
      'updatedAt': FieldValue.serverTimestamp(),
    };
    if (age != null) data['age'] = age;
    if (sports != null && sports.isNotEmpty) data['sports'] = sports;
    await docRef.set(data);
    return docRef.id;
  }

  /// Links an existing self-registered player account to [parentId] using the
  /// player's account email. Returns the linked player, or null when no player
  /// account matches the email. Throws when the account cannot be linked.
  Future<PlayerModel?> linkChildByEmail({
    required String parentId,
    required String email,
  }) async {
    final normalized = email.trim().toLowerCase();
    if (normalized.isEmpty) return null;

    final userSnap = await _firestore
        .collection('users')
        .where('email', isEqualTo: normalized)
        .limit(1)
        .get();
    if (userSnap.docs.isEmpty) return null;

    final userData = userSnap.docs.first.data();
    final childUid = userSnap.docs.first.id;
    if (childUid == parentId) {
      throw Exception('You cannot link your own account');
    }
    if (userData['role'] != 'player') {
      throw Exception('Only player accounts can be linked to a parent');
    }

    final playerRef = _firestore.collection('players').doc(childUid);
    final playerSnap = await playerRef.get();
    if (playerSnap.exists) {
      final existingParent = playerSnap.data()?['parentId'] as String? ?? '';
      if (existingParent == parentId) {
        throw Exception('This player is already linked to you');
      }
      if (existingParent.isNotEmpty) {
        throw Exception('This player is already linked to another parent');
      }
    }

    final name = userData['name'] as String? ?? 'Player';
    await playerRef.set({
      'playerId': childUid,
      'parentId': parentId,
      'name': name,
      'points': 0,
      'rank': 0,
      'championshipWins': 0,
      'tournamentPoints': 0,
      'level': 'Beginner',
      'createdAt': FieldValue.serverTimestamp(),
      'updatedAt': FieldValue.serverTimestamp(),
    }, SetOptions(merge: true));

    return PlayerModel(
      playerId: childUid,
      parentId: parentId,
      name: name,
      points: 0,
      rank: 0,
      championshipWins: 0,
      tournamentPoints: 0,
      level: 'Beginner',
    );
  }

  /// Updates a linked child's profile fields (name, age, sports, avatar, ...).
  Future<void> updateChild(String playerId, Map<String, dynamic> data) async {
    data['updatedAt'] = FieldValue.serverTimestamp();
    await _firestore.collection('players').doc(playerId).update(data);
  }

  /// Unlinks a child so the record can be linked to a different parent.
  Future<void> unlinkChild(String playerId) async {
    await _firestore.collection('players').doc(playerId).update({
      'parentId': '',
      'updatedAt': FieldValue.serverTimestamp(),
    });
  }

  /// Creates a 6-digit family invite PIN valid for 48 hours
  Future<String> createFamilyInvitePin({
    required String parentId,
    double monthlySpendingLimit = 5000.0,
    bool requireBookingApproval = true,
  }) async {
    final pin = (DateTime.now().millisecondsSinceEpoch % 900000 + 100000).toString();
    await _firestore.collection('family_invites').doc(pin).set({
      'pin': pin,
      'parentId': parentId,
      'monthlySpendingLimit': monthlySpendingLimit,
      'requireBookingApproval': requireBookingApproval,
      'createdAt': FieldValue.serverTimestamp(),
      'expiresAt': Timestamp.fromDate(DateTime.now().add(const Duration(hours: 48))),
      'isUsed': false,
    });
    return pin;
  }

  /// Links a child using the 6-digit invite PIN generated by their parent
  Future<bool> linkChildByInvitePin({
    required String childUid,
    required String pin,
  }) async {
    final inviteRef = _firestore.collection('family_invites').doc(pin.trim());
    final inviteSnap = await inviteRef.get();

    if (!inviteSnap.exists) {
      throw Exception('Invalid invite PIN. Please verify the 6-digit code with your parent.');
    }

    final data = inviteSnap.data()!;
    if (data['isUsed'] == true) {
      throw Exception('This invite PIN has already been used.');
    }

    final expiresAt = (data['expiresAt'] as Timestamp?)?.toDate();
    if (expiresAt != null && expiresAt.isBefore(DateTime.now())) {
      throw Exception('This invite PIN has expired. Please ask your parent for a fresh code.');
    }

    final parentId = data['parentId'] as String;
    final limit = (data['monthlySpendingLimit'] as num?)?.toDouble() ?? 5000.0;
    final requireApproval = data['requireBookingApproval'] as bool? ?? true;

    final batch = _firestore.batch();
    batch.update(inviteRef, {'isUsed': true, 'linkedChildUid': childUid});

    final playerRef = _firestore.collection('players').doc(childUid);
    batch.set(playerRef, {
      'parentId': parentId,
      'monthlySpendingLimit': limit,
      'requireBookingApproval': requireApproval,
      'updatedAt': FieldValue.serverTimestamp(),
    }, SetOptions(merge: true));

    final userRef = _firestore.collection('users').doc(childUid);
    batch.set(userRef, {
      'parentId': parentId,
      'monthlySpendingLimit': limit,
      'requireBookingApproval': requireApproval,
      'updatedAt': FieldValue.serverTimestamp(),
    }, SetOptions(merge: true));

    await batch.commit();
    return true;
  }

  /// Updates child monthly spending limit and approval requirement
  Future<void> updateChildSpendingLimit({
    required String playerId,
    required double limit,
    required bool requireApproval,
  }) async {
    await _firestore.collection('players').doc(playerId).update({
      'monthlySpendingLimit': limit,
      'requireBookingApproval': requireApproval,
      'updatedAt': FieldValue.serverTimestamp(),
    });
  }

  /// Streams a single player record.
  Stream<PlayerModel> getChild(String playerId) {
    return _firestore
        .collection('players')
        .doc(playerId)
        .snapshots()
        .map((doc) => PlayerModel.fromDoc(doc));
  }
}
